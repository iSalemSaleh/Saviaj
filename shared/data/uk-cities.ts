// Build a fast lookup by lowercased name. Used by the pass-id generator
// to convert "Manchester" → "MAN" without walking the array each time.
const cityCodeIndex: Map<string, string> = new Map(
  ukCities.map((c) => [c.name.toLowerCase(), c.code]),
);

// Resolve a city name to its 3-letter code. Falls back to the first
// three letters of the input (uppercased + non-alphanum stripped),
// which keeps pass-id generation safe for free-text or unmapped values.
export function getCityCode(cityName: string | null | undefined): string {
  if (!cityName) return "ZZZ";
  const direct = cityCodeIndex.get(cityName.toLowerCase().trim());
  if (direct) return direct;
  const cleaned = cityName.toUpperCase().replace(/[^A-Z]/g, "");
  if (cleaned.length === 0) return "ZZZ";
  return (cleaned + "XXX").slice(0, 3);
}

// Sorted city names for the dropdown UI. Computed once at module load.
